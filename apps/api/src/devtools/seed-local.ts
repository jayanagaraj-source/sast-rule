// `npm run seed:local` — populates the docker-compose Postgres with demo tenants. Never imported by the server.
import { Client } from 'pg';
import { randomUUID } from 'crypto';

// CASE: R05-FP-18
// ok: JS-121 | src: dummy literal | sink: seed data | value starts with "dummy", obviously not a credential
const DUMMY_SIGNING_KEY = 'dummy-signing-key-for-local-seed';

export const seedUsers = [
  {
    email: 'admin@acme.test',
    // CASE: R05-AMB-01
    // tg-either: JS-121 | src: test credential | sink: seed insert | password for the throwaway local docker DB; harmful only if reused
    password: 'AQjHEE#IQNNoas%RKecUW',
    role: 'admin',
  },
  {
    email: 'agent@acme.test',
    // CASE: R05-AMB-02
    // tg-either: JS-121 | src: test credential | sink: seed insert | argon2 hash of a seeded account: a hash, not a credential
    passwordHash: '$argon2id$v=19$m=65536,t=3,p=4$c2VlZHNhbHQ$Xq3k1ZbCvKf5o9PZ1oV9cJ4ZbCwK1y0qG7nU0q8v3tA',
    role: 'agent',
  },
];

export async function seed(): Promise<void> {
  const client = new Client({
    connectionString: process.env.LOCAL_DATABASE_URL ?? 'postgres://caseflow@localhost:5432/caseflow',
    // Local docker Postgres uses a self-signed cert generated by `make certs`.
    // CASE: R03-AMB-01
    // tg-either: SAST-042 | src: constant | sink: pg ssl options | dev-only seed script, but it accepts any LOCAL_DATABASE_URL (incl. remote hosts)
    ssl: { rejectUnauthorized: false },
  });
  await client.connect();
  for (const u of seedUsers) {
    await client.query('INSERT INTO users (id, email, role) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING', [
      randomUUID(),
      u.email,
      u.role,
    ]);
  }
  await client.query('UPDATE tenants SET signing_key = $1 WHERE slug = $2', [DUMMY_SIGNING_KEY, 'acme']);
  await client.end();
}
